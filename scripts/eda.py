    for hi, (a, b) in enumerate(HALVES, 1):
        w(f"- half {hi}: mean px over first 250 GRADED frames ({a}..): home {f(cxmean(home, a, a + 250))}, "
          f"away {f(cxmean(away, a, a + 250))}")
        k = kick[hi]
        w(f"- half {hi}: mean px over first 250 frames from the kick-off frame ({k}..): home {f(cxmean(home, k, k + 250))}, "
          f"away {f(cxmean(away, k, k + 250))}")
        w(f"- half {hi}: mean px over the full half: home {f(cxmean(home, a, b + 1))}, away {f(cxmean(away, a, b + 1))}")
        # goalkeeper proxy: median over frames of the deepest (min px) and most advanced (max px) tracked player
        for nme_, sl in (("home", home), ("away", away)):
            blk = np.where(pres[a:b + 1][:, sl], px[a:b + 1][:, sl], np.nan)
            ok_ = np.isfinite(blk).sum(1) >= 8
            mn, mx = np.nanmin(blk[ok_], axis=1), np.nanmax(blk[ok_], axis=1)
            w(f"  - {nme_}: median per-frame min px {f(np.median(mn))}, max px {f(np.median(mx))} "
              f"(deepest player near x=0 means the team defends x=0)")
        mh = np.median(np.nanmin(np.where(pres[a:b + 1][:, home], px[a:b + 1][:, home], np.nan)[(pres[a:b + 1][:, home]).sum(1) >= 8], axis=1))
        ma_ = np.median(np.nanmin(np.where(pres[a:b + 1][:, away], px[a:b + 1][:, away], np.nan)[(pres[a:b + 1][:, away]).sum(1) >= 8], axis=1))
        w(f"- half {hi}: => {'HOME defends x=0 and attacks towards x=1' if mh < ma_ else 'AWAY defends x=0 and attacks towards x=1, HOME attacks towards x=0'} "
          f"(team whose deepest player is nearer x=0 defends x=0)")
    w(f"- metadata says attack_direction_first_half = `{atd.meta.get('attack_direction_first_half')}`")

    # ---------------- E5 geometry (all frames; masked later)
    dist = np.full(px.shape, np.inf)
    dxx = (px - bx[:, None]) * PX
    dyy = (py - by[:, None]) * PY
    dd = np.hypot(dxx, dyy)
    dist = np.where(pres & P[:, None], dd, np.inf)
    dh = np.where(home[None, :], dist, np.inf).min(1)
    da = np.where(away[None, :], dist, np.inf).min(1)
    dn = np.minimum(dh, da)
    nteam = np.where(np.isfinite(dn), np.where(dh <= da, 0, 1), -1).astype(np.int8)
    dn_ = np.where(np.isfinite(dn), dn, np.nan)
    dh_ = np.where(np.isfinite(dh), dh, np.nan)
    da_ = np.where(np.isfinite(da), da, np.nan)
    gp = G & P
    w("\n## E5. Ball-player geometry (ball-present graded frames)")
    w(f"- frames: {int(gp.sum())}; with at least one tracked player: {int(np.isfinite(dn_[gp]).sum())}")
    q = [5, 25, 50, 75, 90, 95]
    w(f"- nearest player (m): {pct(dn_[gp], q, 2)}")
    w(f"- nearest home player (m): {pct(dh_[gp], q, 2)}")
    w(f"- nearest away player (m): {pct(da_[gp], q, 2)}")
    d0 = dn_[gp]
    d0 = d0[np.isfinite(d0)]
    w("- nearest-player distance: " + ", ".join(
        f"{lab} {f(c)}" for lab, c in [("<1 m", (d0 < 1).mean()), ("<2 m", (d0 < 2).mean()),
                                       ("<3 m", (d0 < 3).mean()), (">5 m", (d0 > 5).mean()),
                                       (">10 m", (d0 > 10).mean())]))
    fl = np.zeros(T, bool)
    fl[1:] = prevok[1:] & (nteam[1:] >= 0) & (nteam[:-1] >= 0) & (nteam[1:] != nteam[:-1])
    ok_pairs = prevok & (nteam >= 0) & (np.roll(nteam, 1) >= 0)
    minutes = (gp & (nteam >= 0)).sum() / FPS / 60
    w(f"- nearest-team flips: {int(fl.sum())} over {f(minutes, 1)} min of ball-present time = "
      f"{f(fl.sum() / minutes, 2)} flips/min (counted only between consecutive present frames; "
      f"{int(ok_pairs.sum())} such frame pairs)")

    # ---------------- E6
    w("\n## E6. Camera / homography as a ball proxy")
    H, rerr, valid = load_homography()
    w(f"- homography rows {len(H)}, valid fraction (all) {f(valid.mean())}, valid in graded {f(valid[G].mean())}; "
      f"reprojection error percentiles (graded valid): {pct(rerr[G & valid], [50, 90, 99], 3)}")
    cx = np.full(T, np.nan)
    cy = np.full(T, np.nan)
    wid = np.full(T, np.nan)
    idx = np.flatnonzero(G & valid)
    cxn, cyn = pixel_to_pitch(H[idx], 960.0, 540.0)
    lxn, _ = pixel_to_pitch(H[idx], 0.0, 540.0)
    rxn, _ = pixel_to_pitch(H[idx], 1920.0, 540.0)
    cx[idx], cy[idx], wid[idx] = cxn, cyn, np.abs(rxn - lxn)
    cxm, cym, widm = cx * PX, cy * PY, wid * PX
    for nme_, a in (("centre-x (m)", cxm), ("centre-y (m)", cym), ("width proxy at y=540 (m)", widm)):
        aa = a[G & np.isfinite(a)]
        w(f"- {nme_}: std {f(aa.std(), 2)}; p1/p50/p99 = {f(np.percentile(aa, 1), 2)} / "
          f"{f(np.percentile(aa, 50), 2)} / {f(np.percentile(aa, 99), 2)}")
    dcx = np.full(T, np.nan)
    dcx[1:] = np.abs(cxm[1:] - cxm[:-1])
    dcx[~prevok] = np.nan
    w(f"- mean |frame-to-frame change| of centre-x: {f(np.nanmean(dcx), 4)} m/frame "
      f"(median {f(np.nanmedian(dcx), 4)}; p99 {f(np.nanpercentile(dcx, 99), 3)})")
    bxm, bym = bx * PX, by * PY
    bm = gp & np.isfinite(cxm)
    w(f"\nOn ball-present graded frames (n={int(bm.sum())}):")
    w(f"- corr(centre-x, ball x) = {f(corr(cxm[bm], bxm[bm]))}; corr(centre-y, ball y) = {f(corr(cym[bm], bym[bm]))}")

    def fit_rmse(feats: list[np.ndarray], y: np.ndarray, mask: np.ndarray) -> tuple[float, float]:
        X = np.column_stack([a[mask] for a in feats] + [np.ones(mask.sum())])
        beta, *_ = np.linalg.lstsq(X, y[mask], rcond=None)
        r = y[mask] - X @ beta
        return float(np.sqrt((r ** 2).mean())), float(np.corrcoef(X @ beta, y[mask])[0, 1])

    r1 = fit_rmse([cxm], bxm, bm)
    w(f"- linear fit ball_x ~ centre_x: RMSE {f(r1[0], 2)} m (multiple R {f(r1[1])}); "
      f"baseline std of ball_x {f(np.nanstd(bxm[bm]), 2)} m")
    best = (-2.0, 0)
    cors = {}
    for L in range(-75, 76):
        if L >= 0:
            a_, b_, h1, h2 = cxm[L:], bxm[:T - L], half[L:], half[:T - L]
        else:
            a_, b_, h1, h2 = cxm[:T + L], bxm[-L:], half[:T + L], half[-L:]
        mk = np.isfinite(a_) & np.isfinite(b_) & (h1 == h2) & (h1 > 0)
        c = corr(a_[mk], b_[mk])
        cors[L] = c
        if np.isfinite(c) and c > best[0]:
            best = (c, L)
    w(f"- lag search corr(centre_x[t+L], ball_x[t]) over L in -75..75: best L = {best[1]} frames, "
      f"corr {f(best[0])}; at L=0 {f(cors[0])}; at L=+-25: {f(cors[25])} / {f(cors[-25])}")
    L = best[1]
    if L >= 0:
        shifted = np.concatenate([cxm[L:], np.full(L, np.nan)])
    else:
        shifted = np.concatenate([np.full(-L, np.nan), cxm[:T + L]])
    bms = gp & np.isfinite(shifted)
    r1s = fit_rmse([shifted], bxm, bms)
    w(f"- at best lag: linear fit RMSE {f(r1s[0], 2)} m (R {f(r1s[1])}, n={int(bms.sum())})")

    cen = np.nanmean(np.where(pres, px, np.nan), axis=1) * PX
    cen_y = np.nanmean(np.where(pres, py, np.nan), axis=1) * PY
    bc = gp & np.isfinite(cen)
    r2 = fit_rmse([cen], bxm, bc)
    w(f"- player centroid x vs ball x: corr {f(corr(cen[bc], bxm[bc]))}, linear fit RMSE {f(r2[0], 2)} m "
      f"(R {f(r2[1])}); centroid-y vs ball y corr {f(corr(cen_y[bc], bym[bc]))}")
    bb = bm & np.isfinite(cen)
    r3 = fit_rmse([cxm, cen], bxm, bb)
    w(f"- two-feature fit ball_x ~ camera centre-x + centroid x: RMSE {f(r3[0], 2)} m (R {f(r3[1])}); "
      f"for reference single-feature camera fit on the same frames {f(fit_rmse([cxm], bxm, bb)[0], 2)} m, "
      f"centroid {f(fit_rmse([cen], bxm, bb)[0], 2)} m. (in-sample fits, 3 coefficients max)")
    mc_p = np.nanmean(dcx[G & P])
    mc_m = np.nanmean(dcx[G & ~P])
    w(f"- camera centre-x mean |change| (m/frame): ball-present frames {f(mc_p, 4)}; ball-missing frames {f(mc_m, 4)}; "
      f"medians {f(np.nanmedian(dcx[G & P]), 4)} / {f(np.nanmedian(dcx[G & ~P]), 4)}")
    wp, wm_ = widm[G & P], widm[G & ~P]
    w(f"- width proxy (m) mean: ball-present {f(np.nanmean(wp), 2)}; ball-missing {f(np.nanmean(wm_), 2)}")

    # ---------------- E7
    tags = load_tags()
    w("\n## E7. Smart Tagging")
    tags["dur"] = (tags.end_s - tags.start_s)
    tags["team"] = tags.tags.map(lambda d: d.get("Team"))
    tags["type"] = tags.tags.map(lambda d: d.get("Type"))
    w(f"- instances: {len(tags)}; tag groups seen: {sorted({k for d in tags.tags for k in d})}")
    w("\n**(a)+(b) per code: count, duration percentiles (s), counts by Team tag**\n")
    w("| code | n | dur p10 / p50 / p90 | Team counts |\n|---|---|---|---|")
    for code, g in tags.groupby("code"):
        p = np.percentile(g.dur, [10, 50, 90])
        tc = g.team.fillna("(none)").value_counts().to_dict()
        w(f"| {code} | {len(g)} | {f(p[0], 1)} / {f(p[1], 1)} / {f(p[2], 1)} | {tc} |")
    low = tags.code.str.lower().str.strip()
    ATT = ["build up", "progression", "creating chances", "attacking transition"]
    isatt = low.isin(ATT)
    isdef = low.str.startswith("defending") | (low == "defensive transition")
    isset = low == "set pieces"
    w(f"\nCode classification used: attacking = {sorted(set(tags.code[isatt]))}; "
      f"defending = {sorted(set(tags.code[isdef]))}; set pieces = {sorted(set(tags.code[isset]))}; "
      f"unclassified = {sorted(set(tags.code[~(isatt | isdef | isset)]))}")

    def cover(sel: pd.Series) -> np.ndarray:
        d = np.zeros(T + 2, np.int32)
        for s_, e_ in zip(tags.start_frame[sel], tags.end_frame[sel]):
            s_, e_ = max(int(s_), 0), min(int(e_), T)
            if e_ > s_:
                d[s_] += 1
                d[e_] -= 1
        return np.cumsum(d)[:T] > 0

    cov_any = cover(pd.Series(True, index=tags.index))
    cov_att, cov_def, cov_set = cover(isatt), cover(isdef), cover(isset)
    w("\n**(c) coverage of graded frames** (half-open [start,end) frames)\n")
    w(f"- any code: {cov_triplet(cov_any, G, P)}")
    w(f"- attacking-phase codes: {cov_triplet(cov_att, G, P)}")
    w(f"- defending codes + defensive transition: {cov_triplet(cov_def, G, P)}")
    w(f"- set pieces: {cov_triplet(cov_set, G, P)}")
    w(f"- attacking OR defending: {cov_triplet(cov_att | cov_def, G, P)}")
    w(f"- base rates: ball present {f(P[G].mean())} of graded frames")
    w("- per-code coverage (all graded / present / missing):")
    for code in sorted(tags.code.unique()):
        cc = cover(tags.code == code)
        w(f"  - {code}: {cov_triplet(cc, G, P)}")

    # (d) mirror
    att_idx = tags.index[isatt]
    def_df = tags[isdef]
    mir = 0
    n_na = 0
    match_counts: dict[tuple[str, str], int] = {}
    for i in att_idx:
        r = tags.loc[i]
        if not r.team or str(r.team).upper() in ("N/A", "NONE"):
            n_na += 1
            continue
        cand = def_df[(def_df.team != r.team) & ((def_df.start_frame - r.start_frame).abs() <= 2)
                      & ((def_df.end_frame - r.end_frame).abs() <= 2)]
        if len(cand):
            mir += 1
            key = (r.code, cand.iloc[0].code)
            match_counts[key] = match_counts.get(key, 0) + 1
    n_att = len(att_idx) - n_na
    w(f"\n**(d) mirror check**: {mir} of {n_att} attacking-phase instances ({f(mir / max(n_att, 1))}) have a "
      f"defending-code instance of the other team with start and end within 2 frames "
      f"({n_na} attacking instances without a usable Team tag skipped). By (attacking code -> defending code):")
    for k, v in sorted(match_counts.items()):
        w(f"  - {k[0]} -> {k[1]}: {v}")
    # also same-team defending overlap check not requested; skip

    # (e) conflict
    teams_seen = sorted({t for t in tags.team.dropna().unique() if str(t).upper() != "N/A"})
    w(f"\n**(e) conflict**: team tag values seen: {teams_seen}")
    if len(teams_seen) >= 2:
        covs = [cover(isatt & (tags.team == t)) for t in teams_seen[:2]]
        both = covs[0] & covs[1]
        anyatt = covs[0] | covs[1]
        w(f"- graded frames where attacking-phase codes of both teams overlap: {f(both[G].mean())} "
          f"({int(both[G].sum())} frames); as share of graded frames covered by any attacking code: "
          f"{f(both[G].sum() / max(anyatt[G].sum(), 1))}")
        for t, c in zip(teams_seen[:2], covs):
            w(f"- attacking coverage of graded frames by {t}: {f(c[G].mean())}")

    # (f) set pieces
    sp = tags[isset].copy()
    sp["Pstart"] = sp.start_frame.map(lambda x: bool(P[min(max(int(x), 0), T - 1)]))
    sp["Pend"] = sp.end_frame.map(lambda x: bool(P[min(max(int(x), 0), T - 1)]))
    w("\n**(f) SET PIECES by Type**\n")
    w("| type | n | ball present at start / missing at start | duration p10/p50/p90 (s) | frac present at start | frac present at end |\n|---|---|---|---|---|---|")
    for ty, g in sp.groupby(sp.type.fillna("(none)")):
        p = np.percentile(g.dur, [10, 50, 90])
        w(f"| {ty} | {len(g)} | {int(g.Pstart.sum())} / {int((~g.Pstart).sum())} | "
          f"{f(p[0], 1)} / {f(p[1], 1)} / {f(p[2], 1)} | {f(g.Pstart.mean(), 3)} | {f(g.Pend.mean(), 3)} |")
    w(f"- all set pieces: present at start {int(sp.Pstart.sum())}, missing at start {int((~sp.Pstart).sum())}")

    # (g) gaps
    at = tags[isatt].sort_values("start_s")
    def gap_hist(df: pd.DataFrame) -> str:
        gaps = (df.start_s.values[1:] - df.end_s.values[:-1])
        edges = [(-1e9, 0, "<0 (overlap)"), (0, 1, "0-1"), (1, 3, "1-3"), (3, 10, "3-10"), (10, 30, "10-30"),
                 (30, 1e9, ">30")]
        return ", ".join(f"{n_}: {int(((gaps >= lo) & (gaps < hi)).sum())}" for lo, hi, n_ in edges) + \
            f" (n={gaps.size})"
    w("\n**(g) gaps between consecutive attacking-phase instances (seconds)**\n")
    w(f"- all teams merged, sorted by start: {gap_hist(at)}")
    for t in teams_seen[:2]:
        w(f"- {t} only: {gap_hist(at[at.team == t])}")

    # ---------------- E8
    w("\n## E8. Semantics check against the public ground truth (frames 11185..18684)")
    gt = pd.read_csv(REPO / "evaluation" / "gt" / "BAR-ATH_possession_gt_public.csv")
    lab = np.full(T, "X", dtype="<U1")
    lab[gt.frame.values] = gt.label.values
    W0, W1 = 11185, 18684
    win = np.zeros(T, bool)
    win[W0:W1 + 1] = True
    w(f"- window labels: " + ", ".join(f"{k}={int(((lab == k) & win).sum())}" for k in "HADX"))

    def side(team) -> str | None:
        s = str(team).lower()
        if "barc" in s:
            return "H"
        if "athl" in s or "atle" in s or "atlet" in s or "bilbao" in s:
            return "A"
        return None
    tags["side"] = tags.team.map(side)
    w(f"- Team tag -> side mapping: {({t: side(t) for t in sorted(tags.team.dropna().unique())})}")
    w("\n**(a) for frames covered by instances of a code with a team tag T (in the window): label == T's side / other side / D**\n")
    w("| code | n frames | = T side | other side | D | X |\n|---|---|---|---|---|---|")
    for code in sorted(tags.code.unique()):
        sub = tags[(tags.code == code) & tags.side.notna()]
        tot = {"own": 0, "other": 0, "D": 0, "X": 0}
        for sd, g in sub.groupby("side"):
            cv = cover_sel = np.zeros(T + 2, np.int32)
            for s_, e_ in zip(g.start_frame, g.end_frame):
                cv[max(int(s_), 0)] += 1
                cv[min(int(e_), T)] -= 1
            cvb = (np.cumsum(cv)[:T] > 0) & win
            l = lab[cvb]
            tot["own"] += int((l == sd).sum())
            tot["other"] += int(((l != sd) & np.isin(l, ["H", "A"])).sum())
            tot["D"] += int((l == "D").sum())
            tot["X"] += int((l == "X").sum())
        n_ = sum(tot.values())
        if n_ == 0:
            continue
        w(f"| {code} | {n_} | {f(tot['own'] / n_, 3)} | {f(tot['other'] / n_, 3)} | {f(tot['D'] / n_, 3)} | {f(tot['X'] / n_, 3)} |")
    # (b)
    trans = np.flatnonzero((lab[1:] != "D") & (lab[:-1] == "D") & np.isin(lab[1:], ["H", "A"])) + 1
    trans = trans[(trans >= W0) & (trans <= W1)]
    sps = sp[(sp.end_frame >= W0) & (sp.start_frame <= W1)]
    offs_s, offs_e = [], []
    for _, r in sps.iterrows():
        if trans.size:
            offs_s.append(int(trans[np.argmin(np.abs(trans - r.start_frame))] - r.start_frame))
            offs_e.append(int(trans[np.argmin(np.abs(trans - r.end_frame))] - r.end_frame))
    w(f"\n**(b)** public D->alive transitions in window: {trans.size}; set-piece instances overlapping window: {len(sps)}")
    for nme_, o in (("transition - start", offs_s), ("transition - end", offs_e)):
        if o:
            w(f"- offset {nme_} (frames): n={len(o)}, mean {f(np.mean(o), 1)}, min {min(o)}, max {max(o)}")
    # (c)
    isD = win & (lab == "D")
    isAl = win & np.isin(lab, ["H", "A"])
    w("\n**(c) mean tracked-player speed (kph) per frame**\n")
    for nme_, mk in (("public-D", isD), ("public-alive", isAl)):
        a = mps[mk]
        w(f"- {nme_}: frames {int(mk.sum())}; mean {f(np.nanmean(a), 2)}; {pct(a, [10, 50, 90], 2)}")
    # (d)
    w("\n**(d) ball presence / speed**\n")
    w(f"- public-D frames with ball present: {f(P[isD].mean())} ({int(P[isD].sum())} of {int(isD.sum())}); "
      f"ball speed (m/s) on those: {pct(bsp[isD & np.isfinite(bsp)], [10, 50, 90], 2)}")
    w(f"- public-alive frames with ball present: {f(P[isAl].mean())} ({int(P[isAl].sum())} of {int(isAl.sum())}); "
      f"ball speed (m/s): {pct(bsp[isAl & np.isfinite(bsp)], [10, 50, 90], 2)}")
    # (e)
    ma = isAl & P & (nteam >= 0)
    labteam = np.where(lab == "H", 0, 1)
    eqm = labteam == nteam
    w("\n**(e) nearest player's team vs public label (ball-present alive frames)**\n")
    w(f"- all: {f(eqm[ma].mean())} (n={int(ma.sum())})")
    m15 = ma & (dn_ < 1.5)
    w(f"- nearest distance < 1.5 m: {f(eqm[m15].mean())} (n={int(m15.sum())})")

    # ---------------- E9
    w("\n## E9. Video container (ffprobe / ffmpeg decode benchmark; no frames written)")
    for src in ("tactical", "broadcast"):
        vp = str(asset_paths(src)["video"])
        try:
            j = json.loads(subprocess.run(
                ["ffprobe", "-v", "error", "-show_streams", "-show_format", "-of", "json", vp],
                capture_output=True, text=True, timeout=300).stdout)
        except Exception as e:  # noqa: BLE001
            w(f"- {src}: ffprobe failed ({type(e).__name__})")
            continue
        fm = j.get("format", {})
        vs = [s for s in j["streams"] if s["codec_type"] == "video"]
        au = [s for s in j["streams"] if s["codec_type"] == "audio"]
        v0 = vs[0]
        nb = v0.get("nb_frames")
        afr = v0.get("avg_frame_rate")
        w(f"- **{src}**: container {fm.get('format_name')}, duration {f(float(fm.get('duration', 'nan')), 1)} s, "
          f"size {f(float(fm.get('size', 0)) / 1e9, 2)} GB, overall bitrate {f(float(fm.get('bit_rate', 0)) / 1e6, 2)} Mb/s")
        w(f"  - video: codec {v0.get('codec_name')} ({v0.get('profile')}), {v0.get('width')}x{v0.get('height')}, "
          f"pix_fmt {v0.get('pix_fmt')}, r_frame_rate {v0.get('r_frame_rate')}, avg_frame_rate {afr}, "
          f"nb_frames {nb}, video bitrate {f(float(v0.get('bit_rate', 0)) / 1e6, 2) if v0.get('bit_rate') else 'n/a'} Mb/s")
        if nb is None:
            try:
                n_, d_ = afr.split("/")
                w(f"  - nb_frames absent; duration x fps = {f(float(v0.get('duration', fm.get('duration'))) * float(n_) / float(d_), 0)}")
            except Exception:  # noqa: BLE001
                pass
        if au:
            for a in au:
                w(f"  - AUDIO: codec {a.get('codec_name')}, {a.get('sample_rate')} Hz, {a.get('channels')} ch, "
                  f"bitrate {a.get('bit_rate')}")
        else:
            w("  - AUDIO: none")
        # keyframe interval from a 60 s packet window in the middle
        try:
            mid = int(float(fm["duration"]) / 2)
            out = subprocess.run(
                ["ffprobe", "-v", "error", "-select_streams", "v:0", "-show_entries", "packet=flags",
                 "-read_intervals", f"{mid}%+60", "-of", "csv=p=0", vp],
                capture_output=True, text=True, timeout=300).stdout.split()
            fl_ = [x.startswith("K") for x in out]
            if fl_ and sum(fl_) > 0:
                w(f"  - keyframes in a 60 s window: {sum(fl_)} of {len(fl_)} packets "
                  f"(mean GOP length {f(len(fl_) / sum(fl_), 1)} frames)")
        except Exception as e:  # noqa: BLE001
            w(f"  - keyframe probe failed ({type(e).__name__})")
    vp = str(asset_paths("tactical")["video"])
    for label, vf in (("native 1920x1080", None), ("scaled to 960x540", "scale=960:540")):
        cmd = ["ffmpeg", "-hide_banner", "-nostdin", "-ss", "1800", "-t", "60", "-i", vp, "-an"]
        if vf:
            cmd += ["-vf", vf]
        cmd += ["-f", "null", "-"]
        t1 = time.perf_counter()
        try:
            r = subprocess.run(cmd, capture_output=True, text=True, timeout=1200)
            dt = time.perf_counter() - t1
            frames = None
            for ln in r.stderr.replace("\r", "\n").split("\n"):
                if ln.strip().startswith("frame="):
                    frames = int(ln.split("frame=")[1].split()[0])
            w(f"- decode 60 s, {label}: {frames} frames in {f(dt, 1)} s wall = {f(frames / dt, 1) if frames else 'n/a'} fps "
              f"({f(frames / dt / 25, 2) if frames else 'n/a'}x real time) (default ffmpeg threading, CPU only)")
        except Exception as e:  # noqa: BLE001
            w(f"- decode {label}: failed ({type(e).__name__})")

    # ---------------- E10
    w("\n## E10. Anomalies (aggregate)")
    zero = (npl == 0) & G
    w(f"- graded frames with zero tracked players: {int(zero.sum())}; with <11 players: {int(((npl < 11) & G).sum())}; "
      f"with >22 players: {int(((npl > 22) & G).sum())}")
    w(f"- ungraded frames with >=10 tracked players: {int(((npl >= 10) & ~G).sum())} of {int((~G).sum())}")
    alld = np.zeros(T, bool)
    alld[1:] = G[1:] & (half[1:] == half[:-1]) & ((pres[1:] & pres[:-1]).sum(1) >= 10) & \
        np.all(~(pres[1:] & pres[:-1]) | ((px[1:] == px[:-1]) & (py[1:] == py[:-1])), axis=1)
    w(f"- graded frames whose player positions are all identical to the previous frame (>=10 common players): {int(alld.sum())}")
    both = P & np.roll(P, 1) & np.roll(P, 2)
    w(f"- ball present while <2 tracked players: {int((G & P & (npl < 2)).sum())} graded frames")
    # duplicate positions (two slots at identical coordinates in a frame)
    dup = 0
    gi = np.flatnonzero(G)
    qx = np.round(px[gi] * 1e5)
    qy = np.round(py[gi] * 1e5)
    key = np.where(pres[gi], qx * 1e7 + qy, np.nan)
    key.sort(axis=1)
    same = (np.diff(key, axis=1) == 0).any(axis=1)
    w(f"- graded frames with two slots at identical coordinates: {int(same.sum())}")
    p_in_half = [np.nanmean(npl[a:b + 1]) for a, b in HALVES]
    w(f"- mean tracked players per frame per half: {f(p_in_half[0], 2)}, {f(p_in_half[1], 2)}")
    w(f"- team slot presence: mean home per graded frame {f(nh[G].mean(), 2)}, away {f(na[G].mean(), 2)}")
    w(f"- ball y/x NaN pattern: x finite but y missing: {int((np.isfinite(bx) ^ np.isfinite(by)).sum())} frames")
    w(f"\n_Runtime: {f(time.time() - t0, 0)} s._")

    Path(args.out).parent.mkdir(parents=True, exist_ok=True)
    Path(args.out).write_text("\n".join(OUT) + "\n", encoding="utf-8")
    print("report written:", args.out, "lines:", len(OUT))


