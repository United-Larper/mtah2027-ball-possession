OUT: list[str] = []


def w(s: str = "") -> None:
    OUT.append(s)


def f(x, nd: int = 4) -> str:
    if x is None or (isinstance(x, float) and not np.isfinite(x)):
        return "nan"
    if isinstance(x, (int, np.integer)):
        return str(int(x))
    return f"{float(x):.{nd}f}"


def pct(a, qs, nd=3) -> str:
    a = np.asarray(a, float)
    a = a[np.isfinite(a)]
    if a.size == 0:
        return "n=0"
    v = np.percentile(a, qs)
    return "n=%d; " % a.size + ", ".join(f"p{q:g}={f(x, nd)}" for q, x in zip(qs, v))


def corr(a, b) -> float:
    a, b = np.asarray(a, float), np.asarray(b, float)
    m = np.isfinite(a) & np.isfinite(b)
    if m.sum() < 3:
        return float("nan")
    return float(np.corrcoef(a[m], b[m])[0, 1])


def runs_in(mask: np.ndarray, segs=HALVES) -> np.ndarray:
    """Lengths of maximal True runs of mask, computed inside each graded segment separately."""
    out = []
    for a, b in segs:
        m = mask[a:b + 1].astype(np.int8)
        d = np.diff(np.concatenate([[0], m, [0]]))
        s, e = np.flatnonzero(d == 1), np.flatnonzero(d == -1)
        out.append(e - s)
    return np.concatenate(out) if out else np.array([], int)


def run_hist(lengths: np.ndarray) -> str:
    rows = ["| bin (frames) | runs | total frames |", "|---|---|---|"]
    for (lo, hi), nme in zip(BINS, BIN_NAMES):
        sel = (lengths >= lo) & (lengths <= hi)
        rows.append(f"| {nme} | {int(sel.sum())} | {int(lengths[sel].sum())} |")
    return "\n".join(rows)


def cov_triplet(cov: np.ndarray, G, P) -> str:
    return (f"all graded {f(cov[G].mean())}; ball-present {f(cov[G & P].mean())}; "
            f"ball-missing {f(cov[G & ~P].mean())}")


