    w(f"- px percentiles: {pct(xs, [0.1, 1, 99, 99.9], 4)}")
    w(f"- py percentiles: {pct(ys, [0.1, 1, 99, 99.9], 4)}")
    # displacement speed per slot (kph)
    dspd = np.full(px.shape, np.nan)
    dspd[1:] = np.hypot((px[1:] - px[:-1]) * PX, (py[1:] - py[:-1]) * PY) * FPS * 3.6
    dspd[~prevok] = np.nan
    sg = ps[G]
    w(f"\n(c) speed field (kph, graded): {pct(sg[np.isfinite(sg)], [5, 50, 95, 99, 99.9], 2)}")
    m = np.isfinite(dspd) & np.isfinite(ps)
    w(f"- corr(speed field, displacement-derived speed kph): {f(corr(ps[m], dspd[m]))} (n={int(m.sum())}); "
      f"median ratio field/disp (disp>3kph) = {f(np.median(ps[m & (dspd > 3)] / dspd[m & (dspd > 3)]), 3)}")
    mr = m & (dspd > 3)
    w(f"- median ratio field / displacement speed in m/s (disp > 3 kph): {f(np.median(ps[mr] / (dspd[mr] / 3.6)), 3)} "
      f"(a value near 1 means the 'kph' field is actually in m/s)")
    fwd = np.full(px.shape, np.nan)
    fwd[:-1] = dspd[1:]
    m2 = np.isfinite(fwd) & np.isfinite(ps)
    w(f"- corr(speed field, forward-difference speed): {f(corr(ps[m2], fwd[m2]))}")
    # (d) presence runs per slot, whole video
    lens = []
    for s in range(px.shape[1]):
        mm_ = pres[:, s].astype(np.int8)
        d = np.diff(np.concatenate([[0], mm_, [0]]))
        lens.append(np.flatnonzero(d == -1) - np.flatnonzero(d == 1))
    lens = np.concatenate(lens)
    w(f"\n(d) continuous presence runs per slot (entire video): {lens.size} runs over {px.shape[1]} slots; "
      f"length percentiles (s): {pct(lens / FPS, [10, 50, 90], 2)}")
    per_slot = [int(((np.diff(np.concatenate([[0], pres[:, s].astype(np.int8), [0]])) == 1)).sum())
                for s in range(px.shape[1])]
    w(f"- runs per slot: min {min(per_slot)}, median {int(np.median(per_slot))}, max {max(per_slot)}")
    w(f"- slots with zero observations: {int((pres.sum(0) == 0).sum())}")
    mps = np.nanmean(np.where(pres, ps, np.nan), axis=1)
    w(f"\n(e) per-frame mean speed over tracked players (kph, graded): {pct(mps[G], [5, 25, 50, 75, 95], 2)}")

